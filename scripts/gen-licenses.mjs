// Generates THIRD_PARTY_LICENSES.md from `cargo metadata` and the npm production dependency tree.
// Usage: node scripts/gen-licenses.mjs   (requires cargo on PATH; run scripts/devenv first)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|SSPL)/i;

// ---- Rust: only crates actually built for the Windows target (normal deps).
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-gnu", "--manifest-path", join(root, "src-tauri", "Cargo.toml")], {
    maxBuffer: 256 * 1024 * 1024,
  }).toString(),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const rootId = meta.resolve.root;
const seen = new Set();
const stack = [rootId];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    // skip dev-only edges
    if (d.dep_kinds.every((k) => k.kind === "dev")) continue;
    stack.push(d.pkg);
  }
}
const rust = [...seen]
  .filter((id) => id !== rootId)
  .map((id) => pkgs.get(id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? `see ${p.license_file}` : "UNKNOWN"), repo: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name));

// ---- npm: production dependencies, transitively.
const npm = [];
const npmSeen = new Set();
function walk(name) {
  if (npmSeen.has(name)) return;
  npmSeen.add(name);
  const pj = join(root, "node_modules", name, "package.json");
  if (!existsSync(pj)) return;
  const p = JSON.parse(readFileSync(pj, "utf8"));
  npm.push({ name, version: p.version, license: typeof p.license === "string" ? p.license : (p.license?.type ?? "UNKNOWN") });
  for (const d of Object.keys(p.dependencies ?? {})) walk(d);
}
const top = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
for (const d of Object.keys(top.dependencies)) walk(d);
npm.sort((a, b) => a.name.localeCompare(b.name));

// A dual license "X OR Y" is fine when one option is permissive.
const flagged = (l) => COPYLEFT.test(l) && !/\b(MIT|Apache-2\.0|BSD|ISC|Zlib|Unlicense)\b/.test(l);
const flags = [...rust, ...npm].filter((x) => flagged(x.license));

const counts = {};
for (const x of [...rust, ...npm]) counts[x.license] = (counts[x.license] ?? 0) + 1;

let md = `# Third-Party Licenses

NexaTerm is MIT licensed. It is built from the open-source components listed below.
This file is generated by \`node scripts/gen-licenses.mjs\` — regenerate it after changing dependencies.

## Summary

- Rust crates compiled into the Windows build: **${rust.length}**
- JavaScript packages bundled into the UI: **${npm.length}**
- Components whose *only* license option is copyleft (GPL/LGPL/MPL/EPL…): **${flags.length}**${flags.length ? " — see below" : ""}

| License expression | Components |
|---|---|
${Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `| ${l} | ${n} |`)
  .join("\n")}

${flags.length ? `## Weak-copyleft components (reviewed)\n\n${flags.map((f) => `- ${f.name} ${f.version}: ${f.license}`).join("\n")}\n\n${flags.every((f) => f.license === "MPL-2.0") ? "All of these are **MPL-2.0**, a *file-level* copyleft license. They are unmodified upstream crates pulled in by Tauri (HTML/CSS processing) and \`dirs\`. MPL-2.0 permits distribution inside a larger work under a different license (MIT) provided the MPL-covered source files remain available — they are published on crates.io at the versions listed. If you modify any of these files, the modified files must be released under MPL-2.0.\n\nNo GPL, LGPL or AGPL component is compiled into NexaTerm.\n" : "**Review required before release.**\n"}` : "No GPL, LGPL or AGPL component is compiled into NexaTerm.\n"}
## Not bundled

- **Microsoft Edge WebView2 Runtime** — provided by Windows; the installer may download Microsoft's bootstrapper. Proprietary Microsoft redistributable, not part of NexaTerm.
- **WebView2Loader.dll** (GNU builds only) — shipped by the \`webview2-com-sys\` crate, Microsoft redistributable under the WebView2 SDK license.
- **NSIS** — used only at build time to produce the installer (zlib license); the generated installer stub is covered by the NSIS license, which permits redistribution.
- Windows tools invoked at runtime (\`ping.exe\`, \`tracert.exe\`, \`wsl.exe\`, shells) are part of Windows or installed by the user.

## Rust crates

| Crate | Version | License |
|---|---|---|
${rust.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}

## JavaScript packages

| Package | Version | License |
|---|---|---|
${npm.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}
`;
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`rust=${rust.length} npm=${npm.length} flagged=${flags.length}`);
for (const f of flags) console.log(`FLAG ${f.name} ${f.version} ${f.license}`);
